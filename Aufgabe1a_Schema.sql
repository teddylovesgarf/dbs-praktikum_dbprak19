-- Einkaufswagen
CREATE TABLE cart (
    cart_id         INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    customer_id     INTEGER NOT NULL,
    cart_time       TIMESTAMP NOT NULL,
    shipping_address VARCHAR(1000) NOT NULL,
    bank_account    VARCHAR(100) NOT NULL,

    CONSTRAINT pk_cart PRIMARY KEY (cart_id),
    CONSTRAINT fk_cart_customer 
        FOREIGN KEY (customer_id) 
        REFERENCES customer (customer_id)  
        ON UPDATE CASCADE 
        ON DELETE RESTRICT
);
--customer kann verschiedene Käufen; Lieferadressen; Kontodaten haben

CREATE TABLE cartposition (
    cart_id              INTEGER       NOT NULL,
    offer_id             INTEGER       NOT NULL,
    --product_id           VARCHAR(50)   NOT NULL,
    --store_id             INTEGER       NOT NULL,
    price_at_purchase    DECIMAL(10,2) NOT NULL,
    quantity             INTEGER       NOT NULL,


    CONSTRAINT pk_cartposition
        PRIMARY KEY (cart_id, offer_id),

    CONSTRAINT fk_cartposition_cart
        FOREIGN KEY (cart_id)
        REFERENCES cart (cart_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_cartposition_offer
        FOREIGN KEY (offer_id)
        REFERENCES offer (offer_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_cartposition_price
        CHECK (price_at_purchase >= 0),

    CONSTRAINT chk_cartposition_quantity
        CHECK (quantity > 0)
        
);


CREATE TABLE review (
    review_id       INTEGER GENERATED BY DEFAULT AS IDENTITY   NOT NULL,
    customer_id     INTEGER       NOT NULL,
    product_id      VARCHAR(50)   NOT NULL,
    rating          INTEGER       NOT NULL,
    helpful         INTEGER,
    summary         VARCHAR(500), 
    review_text     TEXT,
    review_date     DATE,
       

    CONSTRAINT pk_review
        PRIMARY KEY (review_id),

    CONSTRAINT fk_review_customer
        FOREIGN KEY (customer_id)
        REFERENCES customer (customer_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_review_product
        FOREIGN KEY (product_id)
        REFERENCES product (product_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT chk_review_rating
        CHECK (rating BETWEEN 1 AND 5)
);




