CREATE TYPE product_type_enum AS ENUM ('book','music_cd','dvd'); 
CREATE TYPE contributor_rolle AS ENUM ('Autor/in' , 'Künstler/in', 'Schauspieler/in', 'Filmemacher/in', 'Regisseur/in') ; 

CREATE TABLE product(
    product_id      VARCHAR(50) NOT NULL, 
    title           VARCHAR(255) NOT NULL,
    product_type product_type_enum NOT NULL,
    salesrank       INTEGER,
    picture         VARCHAR(1000),
    -- rating wird aus reviews berechnet, daher kein Attribut in der Produkt-Tabelle
    
    CONSTRAINT pk_product 
        PRIMARY KEY (product_id), 

    CONSTRAINT ck_product_salesrank 
        CHECK (salesrank IS NULL OR salesrank > 0)
);  

CREATE TABLE category(
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    category_name VARCHAR(200) NOT NULL,
    parent_category_id INTEGER, --wir haben dann quasi eine tabelle mit category_id und zugehörigen parent_id, der entweder eine zahl sein kann (die wiederum auf eine kategorie zeigt) oder eben NULL weil die Kategorie keine Oberkategorie hat, weil sie selber eine Oberkategorie ist. 

    CONSTRAINT pk_category
        PRIMARY KEY (category_id),

    CONSTRAINT fk_category_parent
        FOREIGN KEY (parent_category_id)
        REFERENCES category (category_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);

CREATE TABLE product_category (
    product_id  VARCHAR(50) NOT NULL,
    category_id INTEGER NOT NULL,

    CONSTRAINT pk_product_category
        PRIMARY KEY (product_id, category_id),

    CONSTRAINT fk_product_category_product
        FOREIGN KEY (product_id)
        REFERENCES product (product_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_product_category_category
        FOREIGN KEY (category_id)
        REFERENCES category (category_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE TABLE similar_products (
    product_id         VARCHAR(50) NOT NULL,
    similar_product_id VARCHAR(50) NOT NULL,

    CONSTRAINT pk_similar_products
        PRIMARY KEY (product_id, similar_product_id),
    
    CONSTRAINT fk_similar_origin
        FOREIGN KEY (product_id) REFERENCES product (product_id) ON DELETE CASCADE,
        
    CONSTRAINT fk_similar_target
        FOREIGN KEY (similar_product_id) REFERENCES product (product_id) ON DELETE CASCADE,

    CONSTRAINT ck_not_self_similar
        CHECK (product_id != similar_product_id)
);

